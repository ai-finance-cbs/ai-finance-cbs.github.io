create or replace function public.save_attendance(p_week integer,entries jsonb) returns void
language plpgsql security definer set search_path='' as $$
declare e record; q integer; t text:=private.active_term();
begin
  perform private.assert_writable(); perform private.require_grader();
  if not exists(select 1 from public.attendance_sessions where term_id=t and week=p_week) then raise exception 'Invalid session.'; end if;
  if entries is null or jsonb_typeof(entries)<>'array' or jsonb_array_length(entries)>5000 then raise exception 'Invalid attendance rows.'; end if;
  for e in select * from jsonb_to_recordset(entries) as x(uni text,status text) order by uni loop
    perform pg_advisory_xact_lock(hashtextextended(t||':student:'||e.uni,0));
    if not exists(select 1 from private.term_roster(t) r where r.uni=e.uni) then raise exception 'Unknown UNI: %',e.uni; end if;
    select i.quiz_week into q from public.grade_items i join public.grades g on g.term_id=i.term_id and g.item_id=i.id
      where i.term_id=t and g.uni=e.uni and i.quiz_week=p_week;
    if e.status is null then
      delete from public.attendance where term_id=t and uni=e.uni and week=p_week;
      if q is not null then insert into public.attendance(term_id,uni,week,status,source_quiz) values(t,e.uni,p_week,'present',q); end if;
    else insert into public.attendance(term_id,uni,week,status,source_quiz,manual_override) values(t,e.uni,p_week,e.status,q,true)
      on conflict(term_id,uni,week) do update set status=excluded.status,source_quiz=excluded.source_quiz,manual_override=true; end if;
  end loop;
end $$;
create or replace function public.save_grades(entries jsonb) returns void
language plpgsql security definer set search_path='' as $$
declare e record; maximum numeric; q integer; t text:=private.active_term();
begin
  perform private.assert_writable(); perform private.require_grader();
  if entries is null or jsonb_typeof(entries)<>'array' or jsonb_array_length(entries)>80000 then raise exception 'Invalid grade rows.'; end if;
  for e in select * from jsonb_to_recordset(entries) as x(uni text,item_id integer,score numeric) order by uni,item_id loop
    perform pg_advisory_xact_lock(hashtextextended(t||':student:'||e.uni,0));
    if not exists(select 1 from private.term_roster(t) r where r.uni=e.uni) then raise exception 'Unknown UNI: %',e.uni; end if;
    select max_points,quiz_week into maximum,q from public.grade_items where term_id=t and id=e.item_id;
    if maximum is null or (e.score is not null and (e.score<0 or e.score>maximum or e.score::text in ('NaN','Infinity','-Infinity') or e.score<>round(e.score,2))) then raise exception 'Invalid score for item %.',e.item_id; end if;
    if e.score is null then delete from public.grades where term_id=t and uni=e.uni and item_id=e.item_id;
    else insert into public.grades(term_id,uni,item_id,score) values(t,e.uni,e.item_id,e.score)
      on conflict(term_id,uni,item_id) do update set score=excluded.score; end if;
    if q is not null then
      if e.score is null then
        delete from public.attendance where term_id=t and uni=e.uni and week=q and source_quiz=q and not manual_override;
        update public.attendance set source_quiz=null where term_id=t and uni=e.uni and week=q;
      else insert into public.attendance(term_id,uni,week,status,source_quiz) values(t,e.uni,q,'present',q)
        on conflict(term_id,uni,week) do update set source_quiz=q,
          status=case when public.attendance.manual_override then public.attendance.status else 'present' end;
      end if;
    end if;
  end loop;
end $$;
