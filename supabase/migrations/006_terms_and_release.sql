grant select(id,title,status,created_at) on public.terms to authenticated;
create policy terms_read on public.terms for select to authenticated using(private.can_read_term(id));
create trigger preview_guard before insert or update or delete on public.terms for each row execute function private.block_preview_write();
create trigger terms_audit after insert or update or delete on public.terms for each row execute function private.audit_class_change();
create policy roster_read on public.roster for select to authenticated using(private.current_role()='instructor' and private.can_read_term(term_id));
create policy sessions_read on public.attendance_sessions for select to authenticated using(private.can_read_term(term_id));
create policy attendance_read on public.attendance for select to authenticated using(private.current_role() in ('instructor','grader') and private.can_read_term(term_id));
create policy sets_read on public.group_sets for select to authenticated using(private.current_role() in ('student','instructor') and private.can_read_term(term_id));
create policy groups_read on public.class_groups for select to authenticated using(private.current_role() in ('student','instructor') and private.can_read_term(term_id));
create policy memberships_read on public.group_memberships for select to authenticated using(private.can_read_term(term_id) and (private.current_role()='instructor' or (private.current_role()='student' and uni=private.current_uni())));
create policy items_read on public.grade_items for select to authenticated using(private.can_read_term(term_id) and (private.current_role() in ('instructor','grader') or (private.current_role()='student' and released)));
create policy grades_read on public.grades for select to authenticated using(private.can_read_term(term_id) and (private.current_role() in ('instructor','grader') or (private.current_role()='student' and uni=private.current_uni() and exists(select 1 from public.grade_items i where i.term_id=grades.term_id and i.id=item_id and i.released))));
create policy assignment_read on public.assignments for select to authenticated using(private.can_read_term(term_id) and (private.current_role() in ('instructor','grader','student') or (private.current_role()='auditor' and auditor_visible)));
create policy lecture_read on public.lecture_files for select to authenticated using(private.can_read_term(term_id) and
  (private.current_role() in ('instructor','grader') or ((private.current_role()='student' or (private.current_role()='auditor' and auditor_visible)) and (released or release_at<=now()))));
create policy announcements_read on public.announcements for select to authenticated using(private.can_read_term(term_id));
do $$ declare t text; begin
  foreach t in array array['assignments','lecture_files','announcements'] loop
    execute format('create policy instructor_insert on public.%I for insert to authenticated with check(private.current_role()=''instructor'' and term_id=private.active_term())',t);
    execute format('create policy instructor_update on public.%I for update to authenticated using(private.current_role()=''instructor'' and term_id=private.active_term()) with check(private.current_role()=''instructor'' and term_id=private.active_term())',t);
    execute format('create policy instructor_delete on public.%I for delete to authenticated using(private.current_role()=''instructor'' and term_id=private.active_term())',t);
  end loop;
end $$;
-- No browser may retag existing data into another term.
revoke all on public.assignments,public.lecture_files from public,anon,authenticated;
grant select,delete on public.assignments,public.lecture_files to authenticated;
grant insert(id,title,due,points,description,deliverable,grading,auditor_visible),update(title,due,points,description,deliverable,grading,auditor_visible) on public.assignments to authenticated;
grant insert(week,title,storage_path,auditor_visible,release_at,released),update(week,title,auditor_visible,release_at,released) on public.lecture_files to authenticated;

revoke all on function private.actor_uni(),private.current_term(),private.can_read_term(text),private.term_roster(text),private.term_snapshot(text,text,text) from public,anon,authenticated;
grant execute on function private.current_term(),private.can_read_term(text) to authenticated;
revoke all on function public.set_student_preview(text,text),public.set_session_times(integer,timestamptz,timestamptz),public.class_data(text) from public,anon;
grant execute on function public.set_student_preview(text,text),public.set_session_times(integer,timestamptz,timestamptz),public.class_data(text) to authenticated;
commit;
