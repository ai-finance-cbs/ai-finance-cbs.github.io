create or replace function public.view_as_student(target_uni text) returns jsonb
language plpgsql stable security definer set search_path='' as $$
begin
  if private.actor_role()<>'instructor' or private.preview_uni() is distinct from target_uni or target_uni is null then raise exception 'Start the read-only student preview first.'; end if;
  return private.student_snapshot(target_uni);
end $$;
create or replace function public.link_student_account(p_email text,p_uni text) returns void
language plpgsql security definer set search_path='' as $$
begin
  perform private.assert_writable(); perform private.require_instructor();
  if p_uni is null then delete from private.student_accounts where email=lower(trim(p_email)); return; end if;
  if not exists(select 1 from public.roster where term_id=private.active_term() and uni=lower(trim(p_uni))) then raise exception 'Student not found on roster.'; end if;
  insert into private.student_accounts(email,uni) values(lower(trim(p_email)),lower(trim(p_uni))) on conflict(email) do update set uni=excluded.uni;
end $$;

