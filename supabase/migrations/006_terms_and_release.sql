create function private.actor_uni() returns text
language sql stable security definer set search_path='' as $$
  select coalesce((select uni from private.test_accounts where email=private.current_email()),
    case when private.current_email() like '%@columbia.edu' then split_part(private.current_email(),'@',1)
    else (select uni from private.student_accounts where email=private.current_email()) end)
$$;
create or replace function private.actor_role() returns text
language plpgsql stable security definer set search_path='' as $$
declare e text:=private.current_email(); r text;
begin
  if e is null then return 'unlisted'; end if;
  select role into r from public.allowlist where email=e;
  if r is not null then return r; end if;
  select role into r from private.test_accounts where email=e;
  if r is not null and private.active_term() is not null then return r; end if;
  if exists(select 1 from public.roster r join public.terms t on t.id=r.term_id
    where r.uni=private.actor_uni() and t.status in ('active','archived-readable')) then return 'student'; end if;
  return 'unlisted';
end $$;
create or replace function private.current_uni() returns text
language sql stable security definer set search_path='' as $$ select coalesce(private.preview_uni(),private.actor_uni()) $$;
create function private.current_term() returns text
language sql stable security definer set search_path='' as $$
  select coalesce(
    (select term_id from private.student_previews where user_id=auth.uid() and private.actor_role()='instructor'),
    case when private.actor_role() in ('instructor','grader','auditor')
      or exists(select 1 from private.test_accounts where email=private.current_email()) then private.active_term()
    else (select t.id from public.terms t join public.roster r on r.term_id=t.id
      where r.uni=private.actor_uni() and t.status in ('active','archived-readable')
      order by (t.status='active') desc,t.created_at desc,t.id desc limit 1) end)
$$;
create function private.can_read_term(p_term text) returns boolean
language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.terms t where t.id=p_term and (
    private.current_role() in ('instructor','grader') or
    (private.current_role()='auditor' and t.status='active') or
    (private.current_role()='student' and t.status in ('active','archived-readable') and (
      exists(select 1 from public.roster r where r.term_id=t.id and r.uni=private.current_uni()) or
      (t.status='active' and exists(select 1 from private.test_accounts a where a.role='student' and a.uni=private.current_uni()))))))
$$;
create or replace function private.assert_writable() returns void
language plpgsql security definer set search_path='' as $$
begin
  if private.preview_uni() is not null then raise exception 'Student preview is read-only. Exit preview before making changes.'; end if;
  if private.current_role()='student' and private.current_term() is distinct from private.active_term() then raise exception 'Archived term is read-only.'; end if;
end $$;
create function private.term_roster(p_term text) returns table(uni text,name text,email text,is_test boolean)
language sql stable security definer set search_path='' as $$
  select r.uni,r.name,r.uni||'@columbia.edu',false from public.roster r where r.term_id=p_term
    and not exists(select 1 from public.allowlist a where a.role in ('auditor','grader','instructor') and
      (a.email=r.uni||'@columbia.edu' or exists(select 1 from private.student_accounts s where s.email=a.email and s.uni=r.uni)))
  union all select t.uni,'Test student '||t.uni,null::text,true from private.test_accounts t
    where p_term=private.active_term() and t.role='student' and t.uni is not null
      and not exists(select 1 from public.roster r where r.term_id=p_term and r.uni=t.uni)
$$;
create or replace function private.class_roster() returns table(uni text,name text,email text,is_test boolean)
language sql stable security definer set search_path='' as $$ select * from private.term_roster(private.current_term()) $$;
-- Access is a read operation, including for former students and preview sessions.
create or replace function public.get_access() returns jsonb
language plpgsql stable security definer set search_path='' as $$
declare e text:=private.current_email(); u text:=private.current_uni(); r text:=private.current_role(); v text:=private.preview_uni(); t text:=private.current_term(); n text;
begin
  if e is null then raise exception 'Sign in with a verified Columbia Google account.'; end if;
  select name into n from private.term_roster(t) where uni=v;
  return jsonb_build_object('email',e,'uni',u,'role',r,'actor_role',private.actor_role(),
    'term_id',t,'read_only',v is not null or (select status<>'active' from public.terms where id=t),
    'needs_uni',e like '%@gsb.columbia.edu' and u is null and r='unlisted',
    'view_as',case when v is null then null else jsonb_build_object('uni',v,'name',coalesce(n,v),'term_id',t) end);
end $$;
drop function public.set_student_preview(text);
create function public.set_student_preview(target_uni text default null,p_term text default null) returns jsonb
language plpgsql security definer set search_path='' as $$
declare t text:=coalesce(p_term,private.active_term());
begin
  -- Preview controls check the real actor, so an instructor can switch or exit directly.
  if private.actor_role()<>'instructor' then raise exception 'Instructor access required.'; end if;
  if target_uni is null then
    delete from private.student_previews where user_id=auth.uid(); return public.get_access();
  end if;
  -- Only readable terms can be previewed; ordinary writes still reject archived terms.
  if not exists(select 1 from public.terms where id=t and status in ('active','archived-readable')) or
    not exists(select 1 from private.term_roster(t) where uni=target_uni) then raise exception 'Student not found.'; end if;
  insert into private.student_previews(user_id,uni,term_id) values(auth.uid(),target_uni,t)
    on conflict(user_id) do update set uni=excluded.uni,term_id=excluded.term_id,started_at=now();
  return public.get_access();
end $$;
create or replace function public.replace_roster(rows jsonb) returns integer
language plpgsql security definer set search_path='' as $$
declare n integer; t text:=private.active_term();
begin
  perform private.assert_writable(); perform private.require_instructor();
  if rows is null or jsonb_typeof(rows)<>'array' or jsonb_array_length(rows) not between 1 and 5000 then raise exception 'Provide 1 to 5000 valid roster rows.'; end if;
  if exists(select 1 from jsonb_to_recordset(rows) as x(uni text,name text) where uni is null or uni !~ '^[a-z]{1,8}[0-9]{1,8}$' or length(coalesce(name,''))>200) then raise exception 'Invalid roster row.'; end if;
  perform pg_advisory_xact_lock(hashtextextended('roster:'||t,0));
  delete from public.roster where term_id=t;
  insert into public.roster(term_id,uni,name) select t,uni,coalesce(name,'') from jsonb_to_recordset(rows) as x(uni text,name text);
  get diagnostics n=row_count; return n;
end $$;
